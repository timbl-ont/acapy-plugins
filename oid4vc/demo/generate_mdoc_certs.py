#!/usr/bin/env python3
"""Generate a TEST-ONLY mdoc IACA root, with its private key, for the demos.

ISO/IEC 18013-5 Annex B IACA profile: self-signed, subject with C and CN,
basicConstraints CA:TRUE pathlen 0 (critical), keyUsage keyCertSign + cRLSign
(critical), subject key identifier, issuer alternative name, CRL distribution
point; validity 10 years (the profile allows up to 20).

The demo signs its document signer (DS) certificate with this IACA at
start-up: it creates a P-256 key in the ACA-Py wallet, requests a CSR for it
from the x509_certs plugin, and issues the DS certificate with the Annex B DS
profile (keyUsage digitalSignature and extendedKeyUsage mdlDS 1.0.18013.5.1.2,
both critical; authority and subject key identifiers; the IACA's issuer
alternative name and CRL distribution point; validity 1 year). The mdoc
x5chain carries only the DS certificate. Give the IACA certificate to verifiers
and test suites as the trust anchor.

Prints JavaScript constants for demo/frontend/index.js. Needs ``cryptography``.
"""

import datetime
import json

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import NameOID

ISSUER_ALT_NAME = x509.UniformResourceIdentifier("https://issuer.example.com")
CRL_URL = "https://issuer.example.com/crl"


def _name(common_name: str) -> x509.Name:
    return x509.Name(
        [
            x509.NameAttribute(NameOID.COUNTRY_NAME, "CA"),
            x509.NameAttribute(NameOID.ORGANIZATION_NAME, "ACA-Py OID4VC Demo"),
            x509.NameAttribute(NameOID.COMMON_NAME, common_name),
        ]
    )


def _crl() -> x509.CRLDistributionPoints:
    return x509.CRLDistributionPoints(
        [
            x509.DistributionPoint(
                full_name=[x509.UniformResourceIdentifier(CRL_URL)],
                relative_name=None,
                reasons=None,
                crl_issuer=None,
            )
        ]
    )


def _pem(cert: x509.Certificate) -> str:
    return cert.public_bytes(serialization.Encoding.PEM).decode()


def generate():
    """Return (iaca_cert, iaca_key)."""
    now = datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0)

    iaca_key = ec.generate_private_key(ec.SECP256R1())
    iaca_name = _name("ACA-Py OID4VC Demo IACA (TEST ONLY)")
    iaca = (
        x509.CertificateBuilder()
        .subject_name(iaca_name)
        .issuer_name(iaca_name)
        .public_key(iaca_key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now)
        .not_valid_after(now + datetime.timedelta(days=3650))
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
        .add_extension(
            x509.KeyUsage(
                digital_signature=False,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=True,
                crl_sign=True,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        .add_extension(
            x509.SubjectKeyIdentifier.from_public_key(iaca_key.public_key()),
            critical=False,
        )
        .add_extension(x509.IssuerAlternativeName([ISSUER_ALT_NAME]), critical=False)
        .add_extension(_crl(), critical=False)
        .sign(iaca_key, hashes.SHA256())
    )
    return iaca, iaca_key


def main():
    """Print the demo constants."""
    iaca, iaca_key = generate()
    iaca_key_pem = iaca_key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    ).decode()
    expiry = f"{iaca.not_valid_after_utc:%Y-%m-%d}"
    print(f"// Generated by demo/generate_mdoc_certs.py; IACA valid until {expiry}.")
    print(f"const iaca_certificate_pem = {json.dumps(_pem(iaca))};")
    print(f"const iaca_private_key_pem = {json.dumps(iaca_key_pem)};")


if __name__ == "__main__":
    main()
