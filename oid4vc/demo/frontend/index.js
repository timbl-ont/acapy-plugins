// mdoc document signer: a P-256 key in the issuer's wallet, whose document signer (DS)
// certificate is issued here by the TEST-ONLY IACA with the ISO/IEC 18013-5 Annex B
// DS profile and stored with the x509_certs plugin (purpose mdoc_ds). The mso_mdoc
// plugin signs through the wallet and never holds the private key.
let mdocDocumentSigner = null;

async function issueDocumentSignerCertificate(csrPem) {
  const iaca = new x509.X509Certificate(iaca_certificate_pem);
  const iacaKey = await webcrypto.subtle.importKey(
    "pkcs8",
    x509.PemConverter.decode(iaca_private_key_pem)[0],
    { name: "ECDSA", namedCurve: "P-256" },
    false,
    ["sign"],
  );
  const csr = new x509.Pkcs10CertificateRequest(csrPem);
  const publicKey = await csr.publicKey.export();
  const notBefore = new Date();
  const notAfter = new Date(notBefore.getTime() + 365 * 24 * 3600 * 1000);
  const serialNumber = randomBytes(16);
  serialNumber[0] &= 0x7f;
  // The DS carries the IACA's issuer alternative name and CRL distribution point.
  const fromIaca = (oid) =>
    new x509.Extension(oid, false, iaca.extensions.find((ext) => ext.type === oid).value);
  const ds = await x509.X509CertificateGenerator.create({
    serialNumber: serialNumber.toString("hex"),
    subject: "C=CA, O=ACA-Py OID4VC Demo, CN=ACA-Py OID4VC Demo Document Signer (TEST ONLY)",
    issuer: iaca.subjectName,
    notBefore,
    notAfter,
    publicKey,
    signingKey: iacaKey,
    signingAlgorithm: { name: "ECDSA", hash: "SHA-256" },
    extensions: [
      new x509.KeyUsagesExtension(x509.KeyUsageFlags.digitalSignature, true),
      new x509.ExtendedKeyUsageExtension(["1.0.18013.5.1.2"], true), // mdlDS
      new x509.AuthorityKeyIdentifierExtension(
        iaca.getExtension(x509.SubjectKeyIdentifierExtension).keyId, false
      ),
      await x509.SubjectKeyIdentifierExtension.create(publicKey, false),
      fromIaca("2.5.29.18"), // issuer alternative name
      fromIaca("2.5.29.31"), // CRL distribution points
    ],
  });
  return ds.toString("pem");
}

async function initializeMdocDocumentSigner() {
  const headers = {
    accept: "application/json",
    "Content-Type": "application/json",
    "Authorization": "Bearer " + token.token,
  };
  if (API_KEY) {
    headers["X-API-KEY"] = API_KEY;
  }
  const post = async (path, body) => {
    const response = await fetch(`${API_BASE_URL}${path}`, { method: "POST", headers, body: JSON.stringify(body) });
    if (!response.ok) {
      throw new Error(`POST ${path}: ${response.status} ${response.statusText} ${await response.text()}`);
    }
    return await response.json();
  };

  try {
    const { multikey } = await post("/wallet/keys", { alg: "p256" });
    logger.info(`Created mdoc document signer wallet key: ${multikey}`);
    const { csr } = await post("/x509/csr", {
      multikey,
      subject: { common_name: "ACA-Py OID4VC Demo Document Signer", country: "CA" },
    });
    const dsCertificatePem = await issueDocumentSignerCertificate(csr);
    await post("/x509/certificates", {
      chain: `${dsCertificatePem}\n${iaca_certificate_pem}`,
      purpose: "mdoc_ds",
    });
    logger.info("Stored the IACA-issued mdoc document signer certificate");

    // Trust the IACA root (not the DS) for mdoc verification: the mso_mdoc verifier
    // reads /mso-mdoc/trust-anchors, and x509_certs /x509/trust-anchors.
    await post("/mso-mdoc/trust-anchors", { certificate_pem: iaca_certificate_pem });
    await post("/x509/trust-anchors", {
      certificate_pem: iaca_certificate_pem,
      purpose: "iaca",
      label: "ACA-Py OID4VC Demo IACA (TEST ONLY)",
    });
    mdocDocumentSigner = { key_type: "wallet", multikey };
  } catch (err) {
    logger.error(`mdoc document signer setup failed: ${err.message}`);
  }
}

