function claimPaths(namespace, labels) {
  return Object.entries(labels).map(([element, name]) => ({
    path: [namespace, element],
    display: [{ name, locale: "en-US" }],
  }));
}

// Leave out optional form fields that were left empty.
function compact(elements) {
  return Object.fromEntries(
    Object.entries(elements).filter(([, value]) => value !== undefined && value !== null && value !== "")
  );
}

// age_over_NN: true from the NNth birthday on (calendar date, UTC).
function ageOver(birthDate, years) {
  const birth = new Date(birthDate);
  return Date.now() >= Date.UTC(birth.getUTCFullYear() + years, birth.getUTCMonth(), birth.getUTCDate());
}

function ageInYears(birthDate) {
  let years = 0;
  while (ageOver(birthDate, years + 1)) years++;
  return years;
}

function optionalInt(value) {
  return value === undefined || value === "" ? undefined : parseInt(value, 10);
}

// Create the credential configuration for a doctype once, then create an exchange for
// the subject and send its offer to the browser. Signing happens in the plugin.
async function issue_mso_mdoc(req, { doctype, displayName, claims, credentialSubject }) {
  const registrationId = req.body.registrationId;
  const emit = (message) => events.emit(`issuance-${registrationId}`, {type: "message", message});
  const debug = (message, data) => events.emit(`issuance-${registrationId}`, {type: "debug-message", message, data});

  if (!mdocDocumentSigner) {
    emit("The mdoc document signer is not set up; check the demo-app log.");
    return;
  }

  const headers = {
    accept: "application/json",
  };
  const commonHeaders = {
    accept: "application/json",
    "Content-Type": "application/json",
    "Authorization": "Bearer " + token.token,
  };
  if (API_KEY) {
    commonHeaders["X-API-KEY"] = API_KEY;
  }
  axios.defaults.withCredentials = true;
  axios.defaults.headers.common["Access-Control-Allow-Origin"] = API_BASE_URL;
  axios.defaults.headers.common["X-API-KEY"] = API_KEY;
  axios.defaults.headers.common["Authorization"] = "Bearer " + token.token;

  if (!mdocSupportedCredIDs[doctype]) {
    const createCredentialSupportedUrl = `${API_BASE_URL}/oid4vci/credential-supported/create/mso-mdoc`;
    const createCredentialSupportedOptions = {
      method: "POST",
      headers: commonHeaders,
      body: JSON.stringify({
        format: "mso_mdoc",
        id: doctype,
        doctype,
        // The plugin signs with this wallet key; its certificate is in x509_certs.
        document_signer: mdocDocumentSigner,
        validity_info: MDOC_VALIDITY_INFO,
        cryptographic_binding_methods_supported: ["jwk"],
        credential_signing_alg_values_supported: ["ES256"],
        proof_types_supported: {
          jwt: {
            proof_signing_alg_values_supported: ["ES256"]
          }
        },
        credential_metadata: {
          claims,
          display: [
            {
              name: displayName,
              locale: "en-US",
              background_image: { uri: MDOC_CARD_BACKGROUND },
            }
          ],
        },
      }),
    };
    emit(`Posting Create Credential Request to: ${createCredentialSupportedUrl}`);
    debug("Request options", createCredentialSupportedOptions);
    const response = await fetch(createCredentialSupportedUrl, createCredentialSupportedOptions);
    if (!response.ok) {
      emit(`Creating the ${doctype} credential configuration failed: ${response.status} ${response.statusText}`);
      return;
    }
    mdocSupportedCredIDs[doctype] = (await response.json()).supported_cred_id;
  }
  const supportedCredId = mdocSupportedCredIDs[doctype];
  logger.info(supportedCredId);

  // IETF Token Status List for revocation: the status_list plugin assigns each mdoc
  // an entry, which goes in the MSO status, recorded against its exchange.
  if (!mdocStatusListIDs[doctype]) {
    const statusListCreateUrl = `${API_BASE_URL}/status-list/defs`;
    const statusListCreateOptions = {
      method: "POST",
      headers: commonHeaders,
      body: JSON.stringify({
        issuer_did: issuerDID,
        list_size: 131072,
        list_type: "ietf",
        shard_size: 131072,
        status_message: [
          { status: "0x00", message: "active" },
          { status: "0x01", message: "inactive" },
        ],
        status_purpose: "revocation",
        status_size: 1,
        supported_cred_id: supportedCredId,
        verification_method: issuerDID + "#0",
      }),
    };
    emit(`Posting Create Status List Request to: ${statusListCreateUrl}`);
    debug("Request options", statusListCreateOptions);
    const response = await fetch(statusListCreateUrl, statusListCreateOptions);
    if (!response.ok) {
      emit(`Creating the ${doctype} status list failed: ${response.status} ${response.statusText}`);
      return;
    }
    mdocStatusListIDs[doctype] = (await response.json()).id;
    emit(`Created Status List ID: ${mdocStatusListIDs[doctype]}`);
  }

  // Create credential exchange
  const exchangeCreateUrl = `${API_BASE_URL}/oid4vci/exchange/create`;
  const exchangeCreateOptions = {
    supported_cred_id: supportedCredId,
    credential_subject: credentialSubject,
    verification_method: issuerDID + "#0",
  };
  emit("Generating Credential Exchange.");
  emit(`Posting Credential Exchange Creation Request to: ${exchangeCreateUrl}`);
  debug("Request options", exchangeCreateOptions);
  let exchangeId;
  try {
    const exchangeResponse = await axios.post(exchangeCreateUrl, exchangeCreateOptions);
    exchangeId = exchangeResponse.data.exchange_id;
  } catch (err) {
    // The plugin validates the subject against the doctype's namespaces here.
    emit(`Credential Exchange creation failed: ${err.response?.status} ${err.response?.statusText || err.message}`);
    return;
  }
  emit(`Received Credential Exchange ID: ${exchangeId}`);

  // Get credential offer and emit QR code as in other flows
  const credentialOfferUrl = `${API_BASE_URL}/oid4vci/credential-offer`;
  const credentialOfferOptions = {
    params: {
      exchange_id: exchangeId,
      user_pin_required: false,
    },
    headers: headers,
  };
  emit("Requesting Credential Offer.");
  emit(`Retrieving Credential Offer from: ${credentialOfferUrl}`);
  debug("Request options", credentialOfferOptions);
  const offerResponse = await axios.get(credentialOfferUrl, credentialOfferOptions);
  const credentialOffer = offerResponse.data;

  const qrcode = credentialOffer.credential_offer || credentialOffer.credential_offer_uri;
  logger.info(JSON.stringify(offerResponse.data));
  logger.info(exchangeId);
  emit(`Sending offer to user: ${qrcode}`);
  events.emit(`issuance-${registrationId}`, {type: "qrcode", credentialOffer, exchangeId, qrcode});
  exchangeCache.set(exchangeId, { exchangeId, credentialOffer, mdocSupportedCredID: supportedCredId, registrationId });

  emit("Begin listening for credential to be issued.");
}

