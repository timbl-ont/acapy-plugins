const POLL_MS = 1000;
const TIMEOUT_MS = 5 * 60 * 1000;

const CLAIM_LABELS = {
  given_name: "Given name",
  family_name: "Family name",
  age_is_over_18: "Age 18 or over",
};

const $ = (id) => document.getElementById(id);
const views = ["start", "scan", "success", "failure"];

// Incremented on every start/cancel so stale polls stop updating the page.
let session = 0;

function show(name) {
  for (const view of views) $(`view-${view}`).hidden = view !== name;
}

function reset() {
  session++;
  $("start-error").hidden = true;
  $("view-scan").classList.remove("scanned");
  show("start");
}

async function start() {
  const current = ++session;
  const button = $("start");
  button.disabled = true;
  $("start-error").hidden = true;
  try {
    const res = await fetch("/api/verify", { method: "POST" });
    const body = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error(body.error || `Request failed (${res.status})`);
    if (current !== session) return;
    $("qr").innerHTML = body.qr; // SVG generated by our server
    $("open-wallet").href = body.request_uri;
    $("scan-status").textContent = "Waiting for a wallet…";
    $("view-scan").classList.remove("scanned");
    show("scan");
    poll(body.id, current, Date.now());
  } catch (err) {
    $("start-error").textContent = err.message;
    $("start-error").hidden = false;
  } finally {
    button.disabled = false;
  }
}

function poll(id, current, startedAt) {
  setTimeout(async () => {
    if (current !== session) return;
    if (Date.now() - startedAt > TIMEOUT_MS) {
      return fail("The request expired before a wallet responded.");
    }
    try {
      const res = await fetch(`/api/verify/${id}`);
      if (res.ok) {
        const result = await res.json();
        if (current !== session) return;
        if (result.state === "presentation-valid") return succeed(result);
        if (result.state === "presentation-invalid") {
          return fail("The wallet's response could not be verified.", (result.errors || []).join("\n"));
        }
        if (result.state === "request-retrieved") {
          $("view-scan").classList.add("scanned");
          $("scan-status").textContent = "Approve the request in your wallet…";
        }
      }
    } catch {
      // transient network error: keep polling
    }
    poll(id, current, startedAt);
  }, POLL_MS);
}

function fillList(list, rows) {
  list.replaceChildren();
  for (const [label, value] of rows) {
    const dt = document.createElement("dt");
    dt.textContent = label;
    const dd = document.createElement("dd");
    if (value instanceof Node) dd.append(value);
    else dd.textContent = value;
    list.append(dt, dd);
  }
}

function yesNo(value) {
  const pill = document.createElement("span");
  pill.className = `pill ${value ? "yes" : "no"}`;
  pill.textContent = value ? "Yes" : "No";
  return pill;
}

function formatDate(seconds) {
  if (typeof seconds !== "number") return null;
  return new Date(seconds * 1000).toLocaleDateString(undefined, {
    year: "numeric", month: "short", day: "numeric",
  });
}

function succeed(result) {
  const claims = result.claims || {};
  const name = [claims.given_name, claims.family_name].filter(Boolean).join(" ");

  const photo = $("photo");
  if (result.picture) {
    photo.src = result.picture;
    photo.hidden = false;
    $("avatar").hidden = true;
  } else {
    photo.removeAttribute("src");
    photo.hidden = true;
    $("avatar").hidden = false;
    $("avatar").textContent = [claims.given_name, claims.family_name]
      .filter(Boolean).map((part) => String(part)[0].toUpperCase()).join("") || "?";
  }

  $("holder-name").textContent = name || "Name not shared";
  const age = $("age-badge");
  age.hidden = typeof claims.age_is_over_18 !== "boolean";
  age.className = `pill ${claims.age_is_over_18 ? "yes" : "no"}`;
  age.textContent = claims.age_is_over_18 ? "18+" : "Under 18";

  fillList($("claims"), Object.entries(CLAIM_LABELS)
    .filter(([key]) => key in claims)
    .map(([key, label]) => [label, typeof claims[key] === "boolean" ? yesNo(claims[key]) : String(claims[key])]));

  const credential = result.credential || {};
  fillList($("credential"), [
    ["Credential", credential.type],
    ["Issuer", credential.issuer],
    ["Issued", formatDate(credential.issued_at)],
    ["Expires", formatDate(credential.expires_at)],
  ].filter(([, value]) => value));

  show("success");
}

function fail(summary, detail) {
  $("failure-summary").textContent = summary;
  $("failure-detail").textContent = detail || "";
  $("failure-detail").hidden = !detail;
  show("failure");
}

$("start").addEventListener("click", start);
$("cancel").addEventListener("click", reset);
for (const button of document.querySelectorAll(".restart")) {
  button.addEventListener("click", () => {
    reset();
    start();
  });
}
